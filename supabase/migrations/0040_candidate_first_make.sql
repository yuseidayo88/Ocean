-- 0040: 候補に「まず作るもの」を書かせる（2026-08-28。社長の
-- 「なんかプランの提案が微妙、何をしたいのかがわかりにくい」）。
--
-- 読み直したら、候補のカードには**行き先しか書いていなかった** —
-- 何ができたら完了か / 誰が買うか / 最初の1人をどこで見つけるか / 条件との相性。
-- どれも「その事業がどんなものか」の説明で、
-- **「これを選んだら、会社は明日から何をするのか」がどこにも無い**。
--
-- 社長が3つを比べるとき知りたいのは、そこ。
-- 行き先が同じくらい良さそうな3案は、**やることが違うから**選べる。
--
-- 名前は「作るもの」で書かせる（「調査する」「検討する」は作るものではない）。
-- 統括AIはこのあと同じゴールから計画を引くので、
-- **ここに書いたものが最初のフェーズの成果物になる**。
alter table public.discovery_candidates
  add column if not exists first_make text[] not null default '{}';

comment on column public.discovery_candidates.first_make is
  'この案を選んだら会社が最初に作るもの（2〜3件・成果物の名前）。社長が3つを比べる材料';
